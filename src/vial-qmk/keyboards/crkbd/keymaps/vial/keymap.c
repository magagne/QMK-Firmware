/* ---------------------------------------------------------------------------
 * Custom keycodes
 * ------------------------------------------------------------------------- */

enum custom_keycodes {

    HID_DragScroll = QK_KB_0,
    LED_DragScroll,
    LCLKx2,
    ExitMouseLayer_mac,
    ExitMouseLayer_win,
};


/* ---------------------------------------------------------------------------
 * Custom keycode processing
 * ------------------------------------------------------------------------- */

bool process_record_user(uint16_t keycode, keyrecord_t *record) {

    switch (keycode)
    {

        case HID_DragScroll:

            drag_scroll_set(record->event.pressed);
            return false;


        case LED_DragScroll:

            tap_code(KC_SCRL);

            return false;


        case LCLKx2:

            if (record->event.pressed) {
                tap_code(KC_BTN1);
                wait_ms(50);
                tap_code(KC_BTN1);
            }

            return false;

        case ExitMouseLayer_mac:
            if (record->event.pressed) {
                auto_mouse_layer_exit_mac();
            }
            return false;

        case ExitMouseLayer_win:
            if (record->event.pressed) {
                auto_mouse_layer_exit_win();
            }
            return false;

    }

    return true;
}


/* ---------------------------------------------------------------------------
 * Drag-scroll initialization and task
 * ------------------------------------------------------------------------- */

void keyboard_post_init_user(void) {

    drag_scroll_init();
    td_accent_init();

}


void housekeeping_task_user(void) {

    drag_scroll_task();
    auto_mouse_layer_task();

}


